//! Every upstream recipe's JSON encoding must equal the Scala capture byte for
//! byte; the captures we deliberately do not host are listed alongside.
//!
//! The captures are the byte-exact HTTP responses in `capture-scala/` (and
//! `capture-scala-csv/`); a recipe is matched to its capture through the `edit`
//! field, which ends with `/<ObjectName>.scala`. Both `tags` and
//! `inherited_tags` are Scala `Set`s, so this also proves the CHAMP iteration
//! order reproduced by `core::scala_hash`.
//!
//! The captures are Kit's and Alex's *full* corpus, but a deployment hosts a
//! subset of it plus its own recipes, so the captures for the recipes it does
//! not host are recorded as deliberately omitted in
//! `fixtures/omitted_recipes.txt` rather than compared.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::PathBuf;

use recibase_core as core;
use serde_json::Value;

fn capture_dir() -> PathBuf {
    if let Ok(dir) = std::env::var("RECIBASE_CAPTURE_DIR") {
        return PathBuf::from(dir);
    }
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let candidates = [
        manifest
            .join("..")
            .join("..")
            .join("..")
            .join("capture-scala"),
        // The repository keeps its own copy of the captures under tools/.
        manifest
            .join("..")
            .join("..")
            .join("tools")
            .join("harness")
            .join("capture-scala"),
        PathBuf::from("/Users/chaos/recibase-work/capture-scala"),
    ];
    candidates
        .iter()
        .find(|dir| dir.is_dir())
        .cloned()
        .unwrap_or_else(|| panic!("no capture-scala directory; set RECIBASE_CAPTURE_DIR"))
}

/// The captured response body of every recipe, keyed by object name.
fn captured_bodies() -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut paths: Vec<PathBuf> = fs::read_dir(capture_dir())
        .expect("read the capture directory")
        .map(|entry| entry.expect("directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "raw"))
        .collect();
    paths.sort();
    for path in paths {
        let raw = fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
        let split = raw
            .windows(4)
            .position(|window| window == b"\r\n\r\n")
            .unwrap_or_else(|| panic!("no header terminator in {}", path.display()));
        let body = String::from_utf8(raw[split + 4..].to_vec())
            .unwrap_or_else(|e| panic!("body of {} is not UTF-8: {e}", path.display()));
        // Only recipe responses carry an `edit` field.
        let Ok(json) = serde_json::from_str::<serde_json::Value>(&body) else {
            continue;
        };
        let Some(edit) = json.get("edit").and_then(|v| v.as_str()) else {
            continue;
        };
        let Some(object_name) = edit
            .strip_suffix(".scala")
            .and_then(|stem| stem.rsplit('/').next())
        else {
            continue;
        };
        // `/recipes/vegetable-primavera` is captured twice; both copies are
        // byte-identical, so the later one simply wins.
        out.insert(object_name.to_string(), body);
    }
    assert!(
        !out.is_empty(),
        "no recipe capture found in {}",
        capture_dir().display()
    );
    out
}

/// The recipe file for an `object_name`: `BeefStroganoff` ->
/// `crates/core/recipes/beef_stroganoff.md`.
fn recipe_source(object_name: &str) -> String {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("recipes")
        .join(format!("{}.md", core::recipe::snake_case(object_name)));
    fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}

/// `edit` points at the recipe's source in the deployment's own repository, not
/// the Scala the capture came from, so it is compared by presence, not value.
fn without_edit(body: &str) -> String {
    const KEY: &str = "\"edit\":\"";
    let Some(start) = body.find(KEY) else {
        return body.to_string();
    };
    let value_start = start + KEY.len();
    let Some(length) = body[value_start..].find('"') else {
        return body.to_string();
    };
    let end = value_start + length;
    format!("{}<edit>{}", &body[..value_start], &body[end..])
}

/// Our own recipes (marked `chaos: true`) are not part of Kit's and Alex's
/// upstream corpus and have no Scala capture, so the byte-for-byte comparison
/// skips them. The list is generated by `crates/core/build.rs` from those marks.
fn is_ours(object_name: &str) -> bool {
    core::recipes::chaos_recipes().contains(&object_name)
}

/// The upstream recipes this deployment deliberately does not host, from
/// `fixtures/omitted_recipes.txt` (`#` comments and blank lines ignored).
const OMITTED: &str = include_str!("fixtures/omitted_recipes.txt");

fn omitted_recipes() -> BTreeSet<String> {
    OMITTED
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_string)
        .collect()
}

/// The recipes and fields whose encoding deliberately differs from the capture,
/// from `fixtures/intentional_differences.txt`.
///
/// A recipe's prose is Markdown rather than the capture's HTML, and a recipe may
/// have been corrected locally after the capture was taken. Anything not listed
/// here must still match byte for byte.
fn intentional_differences() -> BTreeMap<String, BTreeSet<String>> {
    const DIFFERENCES: &str = include_str!("fixtures/intentional_differences.txt");
    let mut out: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for line in DIFFERENCES.lines() {
        // Strip the trailing `# why`, which is documentation for the reader.
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split_whitespace();
        let Some(name) = parts.next() else { continue };
        let fields: BTreeSet<String> = parts
            .next()
            .unwrap_or_default()
            .split(',')
            .map(str::trim)
            .filter(|field| !field.is_empty())
            .map(str::to_string)
            .collect();
        out.insert(name.to_string(), fields);
    }
    out
}

/// The top-level keys whose value differs between our encoding and the capture,
/// ignoring `edit` (it points at each deployment's own repository).
fn differing_fields(actual: &str, expected: &str) -> BTreeSet<String> {
    let actual: Value = serde_json::from_str(actual).expect("our recipe encodes as JSON");
    let expected: Value = serde_json::from_str(expected).expect("the capture is JSON");
    let (Some(actual), Some(expected)) = (actual.as_object(), expected.as_object()) else {
        // A shape that is not an object cannot be excused by a field allowance.
        return BTreeSet::from(["<not an object>".to_string()]);
    };
    // Both directions: a field we serve that the capture has no counterpart for
    // is a difference too.
    let mut fields: BTreeSet<String> = BTreeSet::new();
    for (key, value) in expected {
        if key.as_str() != "edit" && actual.get(key) != Some(value) {
            fields.insert(key.clone());
        }
    }
    for key in actual.keys() {
        if key.as_str() != "edit" && !expected.contains_key(key) {
            fields.insert(key.clone());
        }
    }
    fields
}

/// The body with the permitted fields blanked out of both sides.
///
/// The rest is still compared as a string, so key order, spacing and every
/// unlisted field are checked byte for byte even for an allowlisted recipe. Each
/// field is replaced by its name, so a blanked field cannot accidentally match a
/// different one.
fn mask_fields(body: &str, fields: &BTreeSet<String>) -> String {
    let Ok(mut parsed) = serde_json::from_str::<Value>(body) else {
        return body.to_string();
    };
    let Some(object) = parsed.as_object_mut() else {
        return body.to_string();
    };
    for field in fields {
        if let Some(slot) = object.get_mut(field) {
            *slot = Value::String(format!("<{field}>"));
        }
    }
    core::json::to_string(&parsed)
}

/// The gate must catch every kind of divergence, including on a recipe that has
/// an allowance for some other field. Otherwise the allowance would quietly
/// disable the byte comparison for precisely the recipes whose prose changed.
#[test]
fn the_comparison_catches_added_fields_and_reordered_keys() {
    let expected = r#"{"name":"A","notes":["x"],"method":["y"]}"#;

    // An added field is a difference, in either direction.
    let added = r#"{"name":"A","notes":["x"],"method":["y"],"brand_new":1}"#;
    assert_eq!(
        differing_fields(added, expected),
        BTreeSet::from(["brand_new".to_string()])
    );

    // A reordered body is *not* a field difference, so the field check alone
    // would miss it - the masked byte comparison is what catches it.
    let reordered = r#"{"method":["y"],"notes":["x"],"name":"A"}"#;
    let none: BTreeSet<String> = BTreeSet::new();
    assert_eq!(differing_fields(reordered, expected), none);
    assert_ne!(
        mask_fields(reordered, &none),
        mask_fields(expected, &none),
        "a reordered body must not compare equal to the capture"
    );

    // A non-object body cannot be excused by any allowance.
    assert_eq!(
        differing_fields("[]", expected),
        BTreeSet::from(["<not an object>".to_string()])
    );

    // Masking only blanks the allowed field, leaving the rest to be compared.
    let allowed = BTreeSet::from(["notes".to_string()]);
    let mut ours = expected.replace("\"x\"", "\"markdown\"");
    assert_eq!(
        mask_fields(&ours, &allowed),
        mask_fields(expected, &allowed)
    );
    // ... but a change to an unallowed field alongside it is still visible.
    ours = ours.replace("\"y\"", "\"changed\"");
    assert_ne!(
        mask_fields(&ours, &allowed),
        mask_fields(expected, &allowed)
    );
}

#[test]
fn every_hosted_recipe_equals_its_capture_byte_for_byte() {
    let captures = captured_bodies();
    let recipes = core::recipes::recipes();
    assert!(!recipes.is_empty(), "the recipe registry is empty");

    let allowed = intentional_differences();
    let mut allowances_used: BTreeSet<String> = BTreeSet::new();

    // Every upstream recipe we host still matches its capture byte for byte,
    // except for the fields recorded as deliberate differences.
    let mut hosted: BTreeSet<String> = BTreeSet::new();
    for recipe in recipes {
        let name = &recipe.object_name;
        // Our own (marked `chaos: true`) recipes are not part of the upstream corpus
        // and have no Scala capture; the byte-for-byte comparison ignores them.
        if is_ours(name) {
            continue;
        }
        let expected = captures
            .get(name)
            .unwrap_or_else(|| panic!("no capture whose edit ends with /{name}.scala"));
        let actual = core::json::to_string(&recipe.to_json_with_usage(&[]));

        let permitted = allowed.get(name).cloned().unwrap_or_default();
        let differing = differing_fields(&actual, expected);
        assert_eq!(
            differing, permitted,
            "{name}: the JSON differs from the Scala capture in unexpected fields\n\
             differing: {differing:?}\npermitted: {permitted:?}"
        );
        if !permitted.is_empty() {
            allowances_used.insert(name.clone());
        }

        // Everything the allowance does not cover is compared byte for byte,
        // including the order of the keys that remain.
        assert_eq!(
            without_edit(&mask_fields(&actual, &permitted)),
            without_edit(&mask_fields(expected, &permitted)),
            "{name}: the JSON body differs from the Scala capture outside the \
             fields allowed in intentional_differences.txt"
        );
        hosted.insert(name.clone());
    }

    // An allowance that is no longer needed must be deleted, so the list cannot
    // outlive the difference it documents.
    assert_eq!(
        allowances_used,
        allowed.keys().cloned().collect::<BTreeSet<_>>(),
        "intentional_differences.txt lists a recipe that now matches its capture"
    );

    // Every capture is either a recipe we host or one listed as deliberately
    // omitted: a capture that is neither means a recipe was dropped without
    // recording it, and an omitted name we now host means the list is stale.
    let omitted = omitted_recipes();
    assert!(
        omitted.is_disjoint(&hosted),
        "a recipe is both hosted and listed as omitted"
    );
    let captured: BTreeSet<String> = captures.keys().cloned().collect();
    let accounted: BTreeSet<String> = hosted.union(&omitted).cloned().collect();
    assert_eq!(
        accounted,
        captured,
        "captures must be exactly the hosted upstream recipes plus the omitted list\n\
         only in captures: {:?}\nonly in hosted+omitted: {:?}",
        captured.difference(&accounted).collect::<Vec<_>>(),
        accounted.difference(&captured).collect::<Vec<_>>(),
    );
}

/// The generated `chaos_recipes()` list must agree with the `chaos: true`
/// markers in the files, so a renamed or unmarked recipe cannot slip through.
#[test]
fn chaos_recipes_are_marked_chaos_in_their_file() {
    for object_name in core::recipes::chaos_recipes() {
        let source = recipe_source(object_name);
        assert!(
            core::md::is_ours(&source),
            "{object_name} is listed in chaos_recipes() but its file has no `chaos: true`"
        );
    }

    // ... and the other direction: a marked file must be listed.
    for recipe in core::recipes::recipes() {
        let marked = core::md::is_ours(&recipe_source(&recipe.object_name));
        let listed = core::recipes::chaos_recipes().contains(&recipe.object_name.as_str());
        assert_eq!(
            marked, listed,
            "{}: the file's `chaos` marker and chaos_recipes() disagree",
            recipe.object_name
        );
    }
}
